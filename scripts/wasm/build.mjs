#!/usr/bin/env node
import {readFileSync,writeFileSync,mkdirSync,readdirSync,unlinkSync} from 'node:fs';
import {resolve} from 'node:path';
import {homedir} from 'node:os';
import {execFileSync} from 'node:child_process';
import {frozenHeader,sha} from '../native/build.mjs';
const sdk=process.env.REVERSI_EMSDK??resolve(homedir(),'.local/share/reversi-emsdk');
const compiler=resolve(sdk,'upstream/emscripten/em++'),version=execFileSync(compiler,['--version'],{encoding:'utf8'}).trim();
if(!version.includes('4.0.22'))throw Error('Emscripten 4.0.22 required; run scripts/wasm/setup.sh');
const {header,models,weights}=frozenHeader(),dir=resolve('.local-research/wasm-build');mkdirSync(dir,{recursive:true});
writeFileSync(resolve(dir,'frozen.hpp'),header);
const sources=['native/engine.hpp','native/engine.cpp','native/browser.cpp','scripts/native/build.mjs','scripts/wasm/build.mjs'];
const sourceHashes=Object.fromEntries(sources.map(f=>[f,sha(readFileSync(f))]));
const flags=['-O3','-std=c++17','-Wall','-Wextra','-ffp-contract=off','-fno-fast-math','-fexceptions',
 '-sDISABLE_EXCEPTION_CATCHING=0','-sMODULARIZE=1','-sEXPORT_ES6=1','-sENVIRONMENT=web,worker,node','-sFILESYSTEM=0',
 '-sINITIAL_MEMORY=33554432','-sMAXIMUM_MEMORY=134217728','-sALLOW_MEMORY_GROWTH=1','-sSTACK_SIZE=1048576',
 '-sEXPORTED_FUNCTIONS=["_rv_abi","_rv_build_id","_rv_identity","_rv_create","_rv_destroy","_rv_query"]','-sEXPORTED_RUNTIME_METHODS=["UTF8ToString","HEAPU8"]','--profiling-funcs'];
const fingerprint=sha(JSON.stringify({sourceHashes,header:sha(header),version,flags}));
const name=`engine-${fingerprint.slice(0,16)}`,out=resolve('src/wasm');mkdirSync(out,{recursive:true});
execFileSync(compiler,[...flags,`-DREVERSI_BUILD_ID="${fingerprint}"`,'-I',dir,'native/engine.cpp','native/browser.cpp','-o',resolve(out,`${name}.mjs`)],{stdio:'inherit',env:{...process.env,EMCC_CORES:'2'}});
const artifacts=Object.fromEntries(['mjs','wasm'].map(ext=>[`${name}.${ext}`,sha(readFileSync(resolve(out,`${name}.${ext}`)))]));
const receipt={abi:1,fingerprint,version,flags,sourceHashes,modelHeaderSha256:sha(header),models:{B:'original-production',L:models.L.checksum,P:models.P.checksum},weights,module:`${name}.mjs`,artifacts};
writeFileSync(resolve(out,'manifest.js'),`// Generated by scripts/wasm/build.mjs\nexport default ${JSON.stringify(receipt,null,2)};\n`);
writeFileSync(resolve(dir,'build.json'),JSON.stringify(receipt,null,2)+'\n');console.log(JSON.stringify({fingerprint,artifacts},null,2));

// Remove superseded generated artifacts only after a successful build.
for(const file of readdirSync(out))if(/^engine-[0-9a-f]+\.(mjs|wasm)$/.test(file)&&!Object.hasOwn(artifacts,file))unlinkSync(resolve(out,file));
